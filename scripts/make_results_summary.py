w("## 10. Observations and limitations (from the runs above)\n")
w("- Both LoRA and QLoRA reach 1.000 on the synthetic test set; the merged QLoRA model reproduces 1.000 type / 0.983 severity accuracy on 60 logs. The rules baseline is strong on type (0.872) but weak on severity (0.683); the un-tuned 0.5B model is near chance; the 27B cloud model is good but not perfect (0.944 / 0.800) and costs a network round trip plus rate limits.")
